import assert from "node:assert/strict";
import { chromium } from "@playwright/test";
const b = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH, args: ["--no-sandbox"] });
const c = await b.newContext({ serviceWorkers: "block" });
const p = await c.newPage();
await p.goto(`${process.env.URJD_BASE_URL}/local-access`);
await p.getByTestId("input-local-email").fill("AAO818@gmail.com");
await p.getByTestId("input-local-password").fill("AAO818");
await p.getByTestId("button-local-login").click();
await p.waitForTimeout(600);
assert.ok(!p.url().endsWith("/local-access"));
await p.goto(`${process.env.URJD_BASE_URL}/section/contacts`, { waitUntil: "domcontentloaded" });
const save = p.getByTestId("button-top-save");
await save.waitFor({ state: "visible", timeout: 5000 });
await save.click();
await p.waitForTimeout(250);
await p.goto(`${process.env.URJD_BASE_URL}/section/auditLogs`);
await p.waitForTimeout(300);
assert.ok((await p.locator("body").innerText()).includes("حفظ"));
console.log(JSON.stringify({ status: "PASS", saveButtonVisible: true, saveAuditRecorded: true }));
