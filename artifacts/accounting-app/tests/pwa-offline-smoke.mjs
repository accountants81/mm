import assert from "node:assert/strict";
import { chromium } from "@playwright/test";
const base = process.env.URJD_BASE_URL ?? "http://127.0.0.1:22636";
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH, args: ["--no-sandbox"] });
const context = await browser.newContext({ serviceWorkers: "allow" });
const page = await context.newPage();
const manifest = await context.request.get(`${base}/manifest.webmanifest`);
assert.equal(manifest.status(), 200);
const manifestJson = await manifest.json();
assert.equal(manifestJson.display, "standalone");
assert.equal(manifestJson.lang, "ar");
assert.equal((await context.request.get(`${base}/sw.js`)).status(), 200);
await page.goto(`${base}/local-access`, { waitUntil: "networkidle" });
await page.waitForTimeout(500);
assert.ok(await page.locator('link[rel="manifest"]').count() > 0);
await page.evaluate(async () => { if ("serviceWorker" in navigator) await navigator.serviceWorker.ready; });
await page.reload({ waitUntil: "networkidle" });
await context.setOffline(true);
await page.goto(`${base}/local-access`, { waitUntil: "domcontentloaded" });
assert.ok((await page.locator("body").innerText()).length > 0);
console.log(JSON.stringify({ status: "PASS", manifest: true, serviceWorker: true, offlinePage: true, standalone: true }));
await browser.close();
